#!/usr/bin/env python3
"""Renders docs/program/reconciliation/MODULE_EVIDENCE_MATRIX.md from registers/reconciliation/*.json (deterministic; no new facts)."""
import json, os, sys

STATE = {"routes_registered_no_module_source_located": "UNKNOWN - no source attributed", "partial_source_located": "partial source attributed",
         "engineering_slice_service_db_contract_tests": "engineering slice (service+DB+contract+tests)"}


def render(repo):
    d = os.path.join(repo, "registers", "reconciliation")
    ev = json.load(open(os.path.join(d, "module-evidence.json"), encoding="utf-8"))
    man = json.load(open(os.path.join(d, "manifest.json"), encoding="utf-8"))
    lines = ["# M01-M40 evidence matrix (generated - do not edit)", "",
             "Generated by `tools/reconciliation/render_matrix.py` from `registers/reconciliation/module-evidence.json` at baseline `%s`." % man["baselineSha"], "",
             "Inventory evidence only. A state here is not acceptance, production integration or certification; `UNKNOWN` is not `unbuilt`. Latest CI conclusion is the most recent run of the mapped workflow on ANY branch (see `inputs/ci-runs.json` for the run URL and head SHA) and is not necessarily at the baseline SHA.", "",
             "| Module | Wave | State | Services / anchors | Migrations | Contracts | Tests | Screens (route-status) | Missing facets | Latest mapped CI |", "|---|---|---|---|---|---|---|---|---|---|"]
    for m in ev["modules"]:
        o = m["owned"]
        src = ", ".join(s.replace("services/", "") for s in o["services"]) or ("anchors" if m["anchors"] else "-")
        scr = ", ".join("%d %s" % (v, k.replace("route_registered_domain_adapter_missing", "adapter-missing").replace("existing_module_source_integrated_unaccepted", "integrated-unaccepted")
                                   .replace("source_api_workflow_ci_verified_unaccepted", "ci-verified-unaccepted").replace("api_read_subset_not_clinically_complete", "read-subset")) for k, v in m["screens"]["byRouteStatus"].items())
        ci = ", ".join(sorted({c["latestRunConclusion"] or "none" for c in m["ci"]})) or "none mapped"
        lines.append("| %s %s | %s | %s (%s) | %s | %d | %d | %d | %s | %s | %s |" % (m["id"], m["name"].split(";")[0][:48], m["wave"], STATE[m["state"]], m["confidence"], src, len(o["migrations"]), len(o["contracts"]),
                                                                                   len(o["tests"]), scr, ", ".join(m["missingFacets"]) or "-", ci))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    repo = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
    out = os.path.join(repo, "docs", "program", "reconciliation", "MODULE_EVIDENCE_MATRIX.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8", newline="\n").write(render(repo))
    print("wrote", out)
